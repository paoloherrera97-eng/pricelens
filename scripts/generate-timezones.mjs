// Generates config/timezones.ts — an IANA timezone → ISO 3166-1 country map.
//
// Source: the tzdata `zone1970.tab` and `zone.tab` files shipped with the OS,
// which are the canonical mapping and are in the public domain. Generating from
// them rather than hand-writing a table means the data is real: no invented
// entries, and regenerating picks up tzdata's own corrections.
//
// `zone1970.tab` is the modern table and lists the primary country first when a
// zone spans several. `zone.tab` is the older one; it still carries legacy zone
// names that browsers do report (Asia/Calcutta, Europe/Kiev, Asia/Saigon), so
// both are read and zone1970 wins on conflicts.
//
// This table is loaded lazily at runtime — see lib/geo/detect.ts — because the
// common case never needs it.

import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

const SOURCES = [
  // Lower priority first: later files overwrite earlier ones.
  '/usr/share/zoneinfo/zone.tab',
  '/usr/share/zoneinfo/zone1970.tab',
];

const map = {};

for (const source of SOURCES) {
  if (!existsSync(source)) {
    throw new Error(`Missing tzdata source: ${source}. Install tzdata and re-run.`);
  }

  for (const line of readFileSync(source, 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;

    const [countries, , zone] = line.split('\t');
    if (!countries || !zone) continue;

    // A zone spanning several countries lists them comma-separated, primary
    // first — "the country that contains the most population" per tzdata.
    const primary = countries.split(',')[0].trim();
    if (!/^[A-Z]{2}$/.test(primary)) continue;

    map[zone.trim()] = primary;
  }
}

// Harvest whatever aliases this ICU knows about.
//
// Browsers report legacy zone names — Asia/Calcutta, Europe/Kiev, Asia/Saigon —
// and tzdata's own tables list only the modern ones, so a lookup on a legacy
// name misses. ICU knows both, and asking it which name it resolves each zone
// to recovers the aliases as *data* rather than as a hand-written list that
// would be wrong the next time tzdata moved.
//
// Note that engines disagree on the direction: this ICU resolves Asia/Kolkata
// to Asia/Calcutta, while browsers generally go the other way. Recording both
// spellings against the same country makes the direction irrelevant.
for (const [zone, country] of Object.entries(map)) {
  try {
    const resolved = new Intl.DateTimeFormat('en-US', { timeZone: zone }).resolvedOptions()
      .timeZone;
    if (resolved && !(resolved in map)) map[resolved] = country;
  } catch {
    // A zone this ICU does not know. The tzdata entry still stands.
  }
}

const sorted = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));

const ts = `// GENERATED by scripts/generate-timezones.mjs from tzdata — do not edit by hand.
//
// IANA timezone → ISO 3166-1 alpha-2 country. Where a zone spans several
// countries, tzdata's primary one is used.
//
// Imported dynamically (lib/geo/detect.ts), so it is a separate chunk and never
// lands in the initial bundle.

export const TIMEZONE_COUNTRY: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 2)};
`;

const target = fileURLToPath(new URL('../config/timezones.ts', import.meta.url));
const prettierOptions = await resolveConfig(target);
writeFileSync(target, await format(ts, { ...prettierOptions, filepath: target }));

console.log(
  `${Object.keys(sorted).length} timezones across ${new Set(Object.values(sorted)).size} countries`,
);
